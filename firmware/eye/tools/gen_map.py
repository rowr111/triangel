#!/usr/bin/env python3
"""Generate src/led/map.rs and triangel-previewer/led_map.js with all 600 LED world positions.
Rerun only if the board geometry or composition layout changes, then run tools/gen_geom.py.

    python tools/gen_map.py
    python tools/gen_map.py --check   # fails if either file is out of date
"""

import math
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MAP_RS = ROOT / "src" / "led" / "map.rs"
LED_MAP_JS = ROOT.parent.parent / "triangel-previewer" / "led_map.js"

# Positions from KiCad triangle.kicad_pcb (D1-D24, local board coords in mm). D1, D9 and
# D17 are at the outline corners; on the board they sit 2 to 2.6 mm further in.
LOCAL_LEDS = [
    (108.66,     145),         # D1  - bottom-left corner
    (118.995,    145),         # D2
    (129.33,     145),         # D3
    (139.665,    145),         # D4
    (150,        145),         # D5  - bottom midpoint
    (160.335,    145),         # D6
    (170.67,     145),         # D7
    (181.005,    145),         # D8
    (191.34,     145),         # D9  - bottom-right corner
    (186.1725,   136.049625),  # D10
    (181.005,    127.09925),   # D11
    (175.8375,   118.148875),  # D12
    (170.67,     109.1985),    # D13
    (165.5025,   100.248125),  # D14
    (160.335,     91.29775),   # D15
    (155.1675,    82.347375),  # D16
    (150,         73.397),     # D17 - top (apex) corner
    (144.8325,    82.347375),  # D18
    (139.665,     91.29775),   # D19
    (134.4975,   100.248125),  # D20
    (129.33,     109.1985),    # D21
    (124.1625,   118.148875),  # D22
    (118.995,    127.09925),   # D23
    (113.8275,   136.049625),  # D24
]

# Local board centroid (from spec)
LOCAL_CX = 150
LOCAL_CY = 121.132

# Grid spacing with gap between board edges.
# In perfect tiling, adjacent board centroids are 100/sqrt(3) ~= 57.735mm apart.
# Each 2mm gap between edges increases that distance by 2mm.
BOARD_GAP = 2  # mm between each pair of touching board edges
CENTROID_DIST = 100 / math.sqrt(3)  # 57.735mm, perfect tiling
GRID_K = (CENTROID_DIST + BOARD_GAP) / CENTROID_DIST
H = 100 * math.sqrt(3) / 2 * GRID_K  # row height, scaled
STEP = 50 * GRID_K                    # half-board x step, scaled

# Chain wiring: boards are numbered in wiring order, a snake for shortest inter-row connections.
# Row 1 left->right, row 2 right->left, row 3 left->right, row 4 right->left, row 5.
# Inter-row connections: 9->10, 16->17, 21->22, 24->25 (each ~52mm, one board-step).
# Baochip data wire connects at board 1 (top-left corner of fixture).

# Each board's outline: its three corners in local board coords, for the previewer to draw.
LOCAL_CORNERS = [(100, 150), (200, 150), (150, 63.397)]

# Everything in map.rs above the table.
MAP_RS_HEAD = """\
// Generated by tools/gen_map.py - do not edit by hand. After regenerating it,
// run tools/gen_geom.py.
// 600 LEDs across 25 boards, in wiring order: board 1 D1-D24, then board 2, and so on. Two chains:
//   Chain 1 (PB4, or PB5 on the v3 controller): LEDs 0-287   (288 LEDs) - boards 1-12
//   Chain 2 (PB5, or PB4 on the v3 controller): LEDs 288-599 (312 LEDs) - boards 13-25
// Boards are numbered along the chain, so an LED's index in LED_MAP is its place on the chain.
// Chain snake: row1 left->right, row2 right->left, row3 left->right, row4 right->left, row5.
// Baochip data wires connect at board 1 (chain 1) and board 13 (chain 2).

pub use super::geom::{WORLD_BOT, WORLD_CENTROID_X, WORLD_CENTROID_Y, WORLD_CX, WORLD_H, WORLD_TOP};
pub const LED_COUNT: usize = 600;
// Chain split, for driving the two WS2812 data lines. The previewer sends all
// 600 in one stream and does not need it.
#[cfg(not(feature = "previewer"))]
pub const CHAIN1_LED_COUNT: usize = 288;
#[cfg(not(feature = "previewer"))]
pub const CHAIN2_LED_COUNT: usize = 312;

pub struct Led {
    pub wx:        f32,
    pub wy:        f32,
    pub board_id:  u8,
    pub local_idx: u8,
}

pub static LED_MAP: [Led; LED_COUNT] = [
"""


def r3(v: float) -> float:
    """Round to 3 decimals the way JavaScript's Math.round does (halves go up)."""
    return math.floor(v * 1000 + 0.5) / 1000


def js_num(v: float) -> str:
    """Format a number as JavaScript prints it: 6 rather than 6.0."""
    return str(int(v)) if v == int(v) else repr(v)


def build_boards() -> list[dict]:
    # Build composition table: 25 boards in number order, top-to-bottom, each row in wiring direction.
    # Row r (1..5) has (11 - 2r) boards. Odd position = apex-down, even = apex-up.
    boards = []
    board_id = 1
    for r in range(1, 6):
        count = 11 - 2 * r
        # Position p counts from the left; even rows are wired right to left.
        for p in range(1, count + 1) if r % 2 == 1 else range(count, 0, -1):
            down = p % 2 == 1
            cx = STEP * (r - 1 + p)
            cy = (3 * r - 2) / 3 * H if down else (3 * r - 1) / 3 * H
            boards.append({"id": board_id, "down": down, "cx": cx, "cy": cy})
            board_id += 1
    return boards


def to_world(board: dict, lx: float, ly: float) -> tuple[float, float]:
    # Apex-up  (unrotated): wx = Cx + (lx - LOCAL_CX), wy = Cy + (ly - LOCAL_CY)
    # Apex-down (180deg rot): wx = Cx - (lx - LOCAL_CX), wy = Cy - (ly - LOCAL_CY)
    dx = lx - LOCAL_CX
    dy = ly - LOCAL_CY
    if board["down"]:
        return r3(board["cx"] - dx), r3(board["cy"] - dy)
    return r3(board["cx"] + dx), r3(board["cy"] + dy)


def build_entries(boards: list[dict]) -> list[dict]:
    entries = []
    for board in boards:
        for i, (lx, ly) in enumerate(LOCAL_LEDS):
            wx, wy = to_world(board, lx, ly)
            entries.append({"wx": wx, "wy": wy, "board_id": board["id"], "local_idx": i + 1})
    return entries


def led_map_js(boards: list[dict], entries: list[dict]) -> str:
    lines = [
        f"  {{wx:{js_num(e['wx'])},wy:{js_num(e['wy'])},boardId:{e['board_id']},"
        f"localIdx:{e['local_idx']}}}"
        for e in entries
    ]
    outlines = [
        "  [" + ",".join(f"[{js_num(x)},{js_num(y)}]" for x, y in (to_world(b, lx, ly) for lx, ly in LOCAL_CORNERS)) + "]"
        for b in boards
    ]
    return "\n".join(
        [
            "// Auto-generated by firmware/eye/tools/gen_map.py - do not edit by hand.",
            "// Source: KiCad triangle.kicad_pcb LED positions.",
            f"// {len(entries)} LEDs across {len(boards)} boards, in chain order.",
            "const LED_MAP = [",
            ",\n".join(lines),
            "];",
            "",
            "// Each board's three corners, in board id order.",
            "const BOARD_OUTLINES = [",
            ",\n".join(outlines),
            "];",
            "",
        ]
    )


def map_rs(entries: list[dict]) -> str:
    lines = [
        f"    Led {{ wx: {e['wx']!r}, wy: {e['wy']!r}, board_id: {e['board_id']}, "
        f"local_idx: {e['local_idx']} }},\n"
        for e in entries
    ]
    return MAP_RS_HEAD + "".join(lines) + "];\n"


def main() -> None:
    boards = build_boards()
    entries = build_entries(boards)
    # led_map.js keeps LF endings; map.rs is written like the other Rust sources.
    outputs = [(LED_MAP_JS, led_map_js(boards, entries), "\n"), (MAP_RS, map_rs(entries), None)]
    if "--check" in sys.argv:
        stale = [path for path, body, _ in outputs if not path.exists() or path.read_text(encoding="utf-8") != body]
        if stale:
            raise SystemExit(" and ".join(str(p) for p in stale) + " out of date: run python tools/gen_map.py")
        print(f"{MAP_RS} and {LED_MAP_JS} are up to date")
        return
    for path, body, newline in outputs:
        with path.open("w", encoding="utf-8", newline=newline) as f:
            f.write(body)
    print(f"Wrote {MAP_RS} and {LED_MAP_JS} ({len(entries)} LEDs, {len(boards)} boards)")


if __name__ == "__main__":
    main()
